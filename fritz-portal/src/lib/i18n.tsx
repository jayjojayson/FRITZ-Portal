const DICTS: Record<Lang, Record<string, string>> = { de: {}, en: EN, it: IT };
const LANGS: Lang[] = ['de', 'en', 'it'];

interface I18nContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (s: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({ lang: 'de', setLang: () => {}, t: s => s });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    // Gespeicherte Wahl (bestehender Schlüssel „lang" – Auswahl bleibt nach Updates erhalten),
    // sonst Browsersprache, sonst Deutsch
    const saved = localStorage.getItem('lang') as Lang | null;
    if (saved && LANGS.includes(saved)) return saved;
    const nav = (navigator.language || '').slice(0, 2) as Lang;
    return LANGS.includes(nav) ? nav : 'de';
  });
  useEffect(() => { document.documentElement.setAttribute('lang', lang); }, [lang]);
  const setLang = (l: Lang) => { setLangState(l); localStorage.setItem('lang', l); };
  const dict = DICTS[lang];
  // Optional mit Platzhaltern: t('{n} Geräte', { n: 5 }) – alternativ weiterhin t(...).replace(...)
  const t = (s: string, params?: Record<string, string | number>) => {
    let text = dict[s] ?? s;
    if (params) for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
    return text;
  };
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }

// Bequemlichkeits-Hook: nur die t-Funktion zurückgeben
export function useT() { return useContext(I18nContext).t; }
